import { readFileSync, existsSync, writeFileSync } from 'node:fs'

/* Fetches the live blog posts from Supabase before every build and dev start
 * (npm prebuild / predev) into src/content/blog/posts.generated.js.
 *
 * Posts arrive through the edge function fasta-blog-publish (prometheus-admin,
 * spec docs/fasta-blog-endpoint.md) and are stored in blog_posts. The anon key
 * only sees live posts (RLS: published, not deleted, publish_at reached,
 * images copied), so drafts and scheduled posts cannot leak into the build.
 *
 * No credentials configured → empty list, so a fresh checkout still builds.
 * Credentials configured but the request fails → the build fails on purpose:
 * Render then keeps the previous deploy live instead of publishing a site
 * whose blog has silently vanished.
 */
const OUT = 'src/content/blog/posts.generated.js'

// Render passes the env vars; locally they live in .env.local.
const env = { ...process.env }
for (const f of ['.env.local', '.env']) {
  if (!existsSync(f)) continue
  for (const line of readFileSync(f, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/)
    if (m && env[m[1]] === undefined) env[m[1]] = m[2].replace(/^['"]|['"]$/g, '')
  }
}
const url = env.VITE_SUPABASE_URL
const key = env.VITE_SUPABASE_ANON_KEY

const write = (posts, redirects) => {
  // A second, tiny module so the footer can know whether to link /blog
  // without pulling every article into every page's bundle.
  writeFileSync('src/content/blog/meta.generated.js', `/* Generated by scripts/fetch-blog-posts.mjs. */\nexport const livePostCount = ${posts.length}\n`)
  writeFileSync(OUT, `/* Generated by scripts/fetch-blog-posts.mjs — do not edit, not committed. */\nexport const rows = ${JSON.stringify(posts, null, 2)}\nexport const redirects = ${JSON.stringify(redirects, null, 2)}\n`)
}

if (!url || !key || url.includes('placeholder')) {
  console.warn('[blog] no Supabase credentials, building without posts')
  write([], [])
} else {
  const get = async (path) => {
    const res = await fetch(`${url}/rest/v1/${path}`, { headers: { apikey: key, Authorization: `Bearer ${key}` } })
    if (!res.ok) throw new Error(`[blog] ${path}: HTTP ${res.status} ${await res.text()}`)
    return res.json()
  }
  const posts = await get('blog_posts?select=id,slug,title,meta_title,meta_description,excerpt,content_html,featured_image,author,category,status,publish_at,first_published_at,updated_at&order=publish_at.desc')
  const slugs = await get('blog_post_slugs?select=old_slug,post_id')
  const byId = new Map(posts.map((p) => [p.id, p.slug]))
  const redirects = slugs.filter((s) => byId.has(s.post_id)).map((s) => ({ from: s.old_slug, to: byId.get(s.post_id) }))
  write(posts, redirects)
  console.log(`[blog] ${posts.length} live posts, ${redirects.length} redirects`)
}
